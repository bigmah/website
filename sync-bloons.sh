#!/bin/bash
# Refresh bloons/ from the bloons tree.
#
#   ./sync-bloons.sh [path-to-bloons]
#   ./sync-bloons.sh --no-build [path]     # copy what is already in apps/btd3-web
#
# bloons/ is a build product and nothing else: build_web.sh's output from
# bloons -- the native Rust port of Bloons TD 3, compiled to WebAssembly by
# trunk -- copied in unedited but for one thing (below). It is committed here
# because this site is served straight out of the repository; editing it here
# only means the next refresh throws the edit away.
#
# The one edit: the wasm carries panic-message paths into the builder's cargo
# registry and rustup toolchain, which name the home directory. Those are
# blanked to ~ and padding slashes, the same length, and the integrity hash
# trunk wrote for the wasm into index.html is recomputed to match.
#
# Building needs the wasm32-unknown-unknown target and trunk; see bloons'
# build_web.sh.
set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"

BUILD=1
SRC=""
for a in "$@"; do
  case "$a" in
    --no-build) BUILD=0 ;;
    -h|--help)  sed -n '2,19p' "$0"; exit 0 ;;
    *)          SRC="$a" ;;
  esac
done

# Sibling checkout by default; $BLOONS or an argument override it.
if [ -z "$SRC" ]; then SRC="${BLOONS:-$HERE/../bloons}"; fi
[ -d "$SRC" ] || { echo "no bloons at $SRC (pass a path or set BLOONS)" >&2; exit 1; }
SRC="$(cd "$SRC" && pwd)"
[ -x "$SRC/build_web.sh" ] || { echo "$SRC does not look like bloons" >&2; exit 1; }

OUT="$SRC/apps/btd3-web"

if [ "$BUILD" = 1 ]; then
  command -v trunk >/dev/null || { echo "trunk not found; --no-build to copy apps/btd3-web as it stands" >&2; exit 1; }
  echo "==> building $SRC"
  "$SRC/build_web.sh"
fi

[ -s "$OUT/index.html" ] || { echo "$OUT/index.html is missing or empty -- build first" >&2; exit 1; }
ls "$OUT"/*_bg.wasm >/dev/null 2>&1 || { echo "no wasm in $OUT -- build first" >&2; exit 1; }

echo "==> copying $OUT -> $HERE/bloons"
rsync -a --delete --exclude UPSTREAM "$OUT/" "$HERE/bloons/"
diff -rq --exclude UPSTREAM "$OUT" "$HERE/bloons" >/dev/null

for w in "$HERE"/bloons/*_bg.wasm; do
  perl -0777 -pi -e 'BEGIN { $h = $ENV{HOME}; $r = "~" . ("/" x (length($h) - 1)) } s/\Q$h\E/$r/g' "$w"
  name=$(basename "$w")
  sri="sha384-$(openssl dgst -sha384 -binary "$w" | openssl base64 -A)"
  NAME="$name" SRI="$sri" perl -pi -e \
    's/(href="\.\/\Q$ENV{NAME}\E"[^>]*integrity=")[^"]*/$1$ENV{SRI}/' "$HERE/bloons/index.html"
  grep -q "$sri" "$HERE/bloons/index.html" || { echo "could not update the integrity hash for $name" >&2; exit 1; }
done
! grep -rqF "$HOME" "$HERE/bloons" || { echo "bloons/ still names $HOME" >&2; exit 1; }

rev=$(git -C "$SRC" rev-parse --short HEAD 2>/dev/null || echo unknown)
sub=$(git -C "$SRC" log -1 --pretty=%s 2>/dev/null || echo unknown)
[ -z "$(git -C "$SRC" status --porcelain 2>/dev/null)" ] || rev="$rev-dirty"

# Written with ~ for $HOME, so the file does not name the builder.
case $SRC in "$HOME"/*) shown="~${SRC#"$HOME"}" ;; *) shown=$SRC ;; esac

cat > "$HERE/bloons/UPSTREAM" <<EOF
Generated by sync-bloons.sh -- do not edit anything in this directory.

bloons/ is build_web.sh's output from bloons (apps/btd3-web), copied in whole
and unedited but for home-directory paths blanked in the wasm and its
integrity hash in index.html. Change the game there and run ./sync-bloons.sh
to bring it here.

source     $shown
commit     $rev  $sub
built      $(date -u +%Y-%m-%dT%H:%M:%SZ)
EOF

echo
cat "$HERE/bloons/UPSTREAM"
echo
du -sh "$HERE/bloons"
git -C "$HERE" status --short bloons || true
